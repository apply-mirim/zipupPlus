-- 매물 유형(property_type) × 거래 유형(deal_type) 조합별 계약 체크리스트.
-- get-contract-checklist Edge Function이 이 테이블을 item_order 순으로 조회해 반환한다.
-- property_type: 'apartment' | 'villa' | 'officetel' | 'oneroom'
-- deal_type: 'jeonse' | 'wolse' | 'maemae'
create table if not exists public.contract_checklists (
  id uuid primary key default gen_random_uuid(),
  property_type text not null,
  deal_type text not null,
  item_order int not null,
  item_title text not null,
  item_description text not null,
  -- legal_terms.term과 매칭해 조문 원문/쉬운 설명을 같이 보여주기 위한 참고용 텍스트.
  -- legal_terms에 아직 없는 용어여도 상관없다 — get-contract-checklist가 못 찾으면
  -- 이 텍스트만 그대로 두고 링크(officialDefinition/plainExplanation)는 null로 반환한다.
  related_term text,
  unique (property_type, deal_type, item_order)
);

alter table public.contract_checklists enable row level security;

-- legal_terms와 동일한 패턴: 체크리스트 내용 자체는 민감하지 않으므로 읽기는 공개.
create policy "Anyone can read contract checklists"
  on public.contract_checklists
  for select
  to anon, authenticated
  using (true);

revoke insert, update, delete, truncate on public.contract_checklists from anon, authenticated;

